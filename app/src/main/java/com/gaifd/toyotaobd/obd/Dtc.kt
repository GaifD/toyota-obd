/** Код ошибки и где он записан. */
data class Dtc(val code: String, val kind: Kind, val ecu: String) {
    enum class Kind(val label: String) {
        STORED("сохранена"), PENDING("ожидающая"), PERMANENT("постоянная")
    }

    val info: DtcInfo get() = DtcBook.info(code)
    val description: String get() = info.title
    val ecuName: String get() = Dtcs.ecuName(ecu)
}

object Dtcs {
    fun decode(b1: Int, b2: Int): String? {
        if (b1 == 0 && b2 == 0) return null
        val letter = "PCBU"[(b1 shr 6) and 3]
        return letter + "%01X%01X%02X".format((b1 shr 4) and 3, b1 and 0x0F, b2)
    }

    /** Разобрать ответ режимов 03 / 07 / 0A. На CAN первым идёт количество, на старых протоколах — нет. */
    fun parse(r: EcuReply, kind: Dtc.Kind, can: Boolean): List<Dtc> {
        val start = if (can) 2 else 1
        val out = mutableListOf<Dtc>()
        var i = start
        while (i + 1 < r.data.size) {
            decode(r.data[i], r.data[i + 1])?.let { out += Dtc(it, kind, r.ecu) }
            i += 2
        }
        return out
    }

    fun ecuName(ecu: String): String = when (ecu.uppercase()) {
        "7E8", "10" -> "Двигатель"
        "7E9", "18" -> "Коробка / трансмиссия"
        "7EA" -> "Гибридная система"
        "7EB" -> "Гибридная батарея"
        "7EC" -> "Блок 7EC"
        "7C8" -> "Приборная панель"
        else -> "Блок $ecu"
    }

    /** Ошибки, при которых стоит открыть экран катализатора. */
    fun isCatalystRelated(code: String): Boolean =
        code in setOf("P0420", "P0421", "P0422", "P0430", "P0431", "P0432") ||
            code.startsWith("P013") || code.startsWith("P014") || code.startsWith("P015") || code.startsWith("P016") ||
            code.startsWith("P030") || code in setOf("P0171", "P0172", "P0174", "P0175", "P2195", "P2196", "P2197", "P2198")

