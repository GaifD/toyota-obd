    fun knownTitle(code: String): String? = known[code]

    fun describe(code: String): String {
        known[code]?.let { return it }
        if (code.length < 5) return "Неизвестный код"
        val sys = code[0]
        val generic = code[1] == '0' || code[1] == '2'
        val tail = if (generic) "" else " (код производителя)"
        return when (sys) {
            'P' -> when {
                code.startsWith("P0A") || code.startsWith("P0B") || code.startsWith("P0C") -> "Гибридная система$tail"
                code[2] == '0' || code[2] == '1' -> "Топливо и воздух, смесь$tail"
                code[2] == '2' -> "Топливо, форсунки, турбо$tail"
                code[2] == '3' -> "Зажигание и пропуски$tail"
                code[2] == '4' -> "Вспомогательные системы выбросов$tail"
                code[2] == '5' -> "Скорость, холостой ход, вспомогательные входы$tail"
                code[2] == '6' -> "Блок управления и его выходы$tail"
                code[2] in '7'..'9' -> "Трансмиссия$tail"
                else -> "Силовой агрегат$tail"
            }
            'B' -> "Кузов (подушки, климат, свет)$tail"
            'C' -> "Шасси (ABS, тормоза, рулевое)$tail"
            'U' -> "Связь между блоками$tail"
            else -> "Неизвестный код"
        }
    }
