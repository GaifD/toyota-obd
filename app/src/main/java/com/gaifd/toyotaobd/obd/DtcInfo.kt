    )

    fun info(code: String): DtcInfo {
        val fam = family(code)
        val title = Dtcs.knownTitle(code) ?: fam?.second ?: Dtcs.describe(code)
        if (code in stop) {
            val urg = if (code in setOf("P0A80", "P0A7F", "P3190", "P3191")) Urgency.SOON else Urgency.STOP
            return DtcInfo(title, urg, emptyList(), stopAdvice[code] ?: "")
        }
        val a = fam?.let { advice[it.first] }
        if (a != null) return DtcInfo(title, a.first, a.second, a.third)
        val (urg, adv) = when (code.firstOrNull()) {
            'B' -> Urgency.DRIVE to "Кузовная система (подушки, свет, климат). Если это подушки — к мастеру."
            'C' -> Urgency.SOON to "Шасси: ABS, тормоза, рулевое. Проверь, нормально ли тормозит машина."
            'U' -> Urgency.SOON to "Блоки плохо связываются между собой: разъёмы, питание, иногда севший аккумулятор 12 В."
            else -> Urgency.SOON to "Нужна диагностика."
        }
        return DtcInfo(title, urg, emptyList(), adv)
    }
