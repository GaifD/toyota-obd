package com.gaifd.toyotaobd.obd

/** Насколько срочно. */
enum class Urgency(val label: String) {
    DRIVE("Можно ездить, проверить при случае"),
    SOON("К мастеру в ближайшее время"),
    STOP("Остановись и не продолжай движение"),
}

/** Расшифровка кода: что это, насколько срочно, частые причины, что сделать первым. */
data class DtcInfo(val title: String, val urgency: Urgency, val causes: List<String>, val advice: String)

/**
 * Справочник кодов. Точные описания для частых кодов, остальные стандартные коды собираются
 * по семействам (датчики по рядам, форсунки и катушки по цилиндрам и т.д.), а для совсем редких —
 * описание системы. Причины и советы — для семейств, а не для каждого из тысяч кодов.
 */
object DtcBook {
    private val o2Suffix = listOf("цепь", "низкое напряжение", "высокое напряжение", "медленный отклик", "нет активности", "подогрев — цепь")

    /** Семейства стандартных кодов: (код → название) или null. */
    private fun family(code: String): Pair<String, String>? {
        if (code.length != 5) return null
        val sys = code[0]
        val n = code.substring(1).toIntOrNull(16) ?: return null   // P0420 → 0x0420
        val dec = code.substring(1).toIntOrNull()                     // P0420 → 420 (для чисто цифровых)
        if (sys != 'P') return null
        if (dec != null && code[1] == '0') {
            when (dec) {
                in 10..25 -> return "vvt" to "Изменение фаз газораспределения (VVT), ряд ${if (dec < 20) 1 else 2}"
                in 30..64 -> return "o2heat" to "Подогрев датчика кислорода — цепь управления"
                in 100..104 -> return "maf" to "Датчик расхода воздуха (MAF)"
                in 105..109 -> return "map" to "Датчик давления во впуске (MAP)"
                in 110..114 -> return "iat" to "Датчик температуры воздуха на впуске"
                in 115..119 -> return "ect" to "Датчик температуры охлаждающей жидкости"
                in 120..124, in 220..229 -> return "tps" to "Датчик положения дросселя/педали"
                in 130..167 -> {
                    val (bank, sensor, base) = when (dec) {
                        in 130..135 -> Triple(1, 1, 130)
                        in 136..141 -> Triple(1, 2, 136)
                        in 142..147 -> Triple(1, 3, 142)
                        in 150..155 -> Triple(2, 1, 150)
                        in 156..161 -> Triple(2, 2, 156)
                        in 162..167 -> Triple(2, 3, 162)
                        else -> return "o2" to "Датчик кислорода"
                    }
                    val where = if (sensor == 1) "до катализатора" else "после катализатора"
                    return "o2" to "Датчик кислорода, ряд $bank $where — ${o2Suffix[dec - base]}"
                }
                in 170..175 -> return "trim" to "Топливная коррекция, ряд ${if (dec < 173) 1 else 2}"
                in 201..212 -> return "inj" to "Форсунка цилиндра ${dec - 200} — цепь"
                in 261..296 -> {
                    val cyl = (dec - 261) / 3 + 1
                    val t = listOf("низкий сигнал цепи", "высокий сигнал цепи", "отклонение баланса")[(dec - 261) % 3]
                    return "inj" to "Форсунка цилиндра $cyl — $t"
                }
                300 -> return "misfire" to "Случайные пропуски зажигания"
                in 301..312 -> return "misfire" to "Пропуски зажигания в цилиндре ${dec - 300}"
                in 325..334 -> return "knock" to "Датчик детонации, ряд ${if (dec < 330) 1 else 2}"
                in 335..339 -> return "ckp" to "Датчик положения коленвала"
                in 340..349 -> return "cmp" to "Датчик положения распредвала"
                in 351..362 -> return "coil" to "Катушка зажигания цилиндра ${dec - 350} — цепь"
                in 400..409 -> return "egr" to "Система рециркуляции отработавших газов (EGR)"
                in 410..419 -> return "air" to "Система вторичного воздуха"
                in 420..424 -> return "cat" to "Катализатор, ряд 1 — эффективность ниже порога"
                in 430..434 -> return "cat" to "Катализатор, ряд 2 — эффективность ниже порога"
                in 440..459 -> return "evap" to "Система улавливания паров топлива (EVAP)"
                in 460..464 -> return "level" to "Датчик уровня топлива"
                in 480..485 -> return "fan" to "Вентилятор охлаждения — цепь"
                in 500..503 -> return "vss" to "Датчик скорости автомобиля"
                in 505..509 -> return "idle" to "Система холостого хода"
                in 560..563 -> return "volt" to "Напряжение бортсети 12 В"
                in 600..699 -> return "ecu" to "Блок управления двигателем — внутренняя ошибка или выход"
                in 700..899 -> return "trans" to "Трансмиссия"
            }
        }
        if (code.startsWith("P0A") || code.startsWith("P0B") || code.startsWith("P0C") || code.startsWith("P0D")) {
            return "hybrid" to "Гибридная система"
        }
        if (code.startsWith("P3")) return "hybrid" to "Гибридная система Toyota (код производителя)"
        if (code.startsWith("P2")) {
            val d = code.substring(1).toIntOrNull()
            if (d != null) when (d) {
                in 2195..2198 -> return "af" to "Датчик A/F до катализатора — показания залипли"
                in 2237..2243 -> return "af" to "Датчик A/F до катализатора — цепь"
                in 2400..2420 -> return "evap" to "Система улавливания паров топлива (EVAP)"
                in 2440..2445 -> return "air" to "Система вторичного воздуха"
            }
            if (code.startsWith("P2A0")) return "af" to "Датчик A/F до катализатора"
            return "engine" to "Двигатель, топливо и выбросы"
        }
        if (n in 0x1000..0x1FFF) return "engine" to "Двигатель (код производителя)"
        return null
    }

