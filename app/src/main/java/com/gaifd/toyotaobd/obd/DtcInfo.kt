    /** Коды, при которых ехать дальше нельзя. */
    private val stop = setOf("P0A93", "P0AA6", "P0A7F", "P0A80", "P3000", "P0217", "P0524", "P3190", "P3191")

    private val stopAdvice = mapOf(
